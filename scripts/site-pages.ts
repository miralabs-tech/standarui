import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

export const MARKER = "<!-- generated by scripts/site-pages.ts -->";
export const LOCALES = ["en", "fr"] as const;
export type Locale = (typeof LOCALES)[number];

const MANIFEST = path.join(root, "packages/react/api/manifest.json");

export function pagePath(locale: Locale, component: string): string {
  return path.join(root, "site/content", locale, "components", `${component}.md`);
}

export function titleOf(component: string): string {
  return component
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

export function readComponents(): string[] {
  const manifest = JSON.parse(readFileSync(MANIFEST, "utf8")) as {
    components: Record<string, unknown>;
  };
  return Object.keys(manifest.components).sort();
}

const COPY: Record<Locale, { description: string; intro: string; heading: string }> = {
  en: {
    description: "API of the {name} component: props, anatomy and CSS variables.",
    intro:
      "Reference for the `{name}` component: its props, its parts and the CSS variables it exposes.",
    heading: "Props",
  },
  fr: {
    description: "API du composant {name} : props, anatomie et variables CSS.",
    intro:
      "Référence du composant `{name}` : ses props, ses parties et les variables CSS qu'il expose.",
    heading: "Props",
  },
};

export function renderPage(locale: Locale, component: string): string {
  const name = titleOf(component);
  const copy = COPY[locale];
  return [
    "---",
    `title: ${name}`,
    `description: ${copy.description.replace("{name}", name)}`,
    "---",
    "",
    MARKER,
    "",
    copy.intro.replace("{name}", name),
    "",
    `## ${copy.heading}`,
    "",
    `\`\`\`props ${component}`,
    "```",
    "",
  ].join("\n");
}

export function isGenerated(file: string): boolean {
  return existsSync(file) && readFileSync(file, "utf8").includes(MARKER);
}

export function writePages(): { written: string[]; skipped: string[] } {
  const written: string[] = [];
  const skipped: string[] = [];
  for (const component of readComponents()) {
    for (const locale of LOCALES) {
      const file = pagePath(locale, component);
      if (existsSync(file) && !isGenerated(file)) {
        skipped.push(file);
        continue;
      }
      writeFileSync(file, renderPage(locale, component));
      written.push(file);
    }
  }
  return { written, skipped };
}

if (import.meta.main) {
  const { written, skipped } = writePages();
  console.log(`site-pages: ${written.length} written, ${skipped.length} kept hand-written`);
}
